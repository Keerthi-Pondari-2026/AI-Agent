import { useEffect } from 'react'
import { Link } from 'react-router-dom'
import {
  AlertCircle,
  ArrowLeft,
  CheckCircle2,
  Loader2,
  RotateCcw,
  Sparkles,
  TrendingUp,
} from 'lucide-react'
import { useInterview } from '../context/InterviewContext'
import { useAuth } from '../context/AuthContext'

export function Results() {
  const { isDemoMode } = useAuth()
  const {
    config,
    results,
    resultsIllustrative,
    interviewId,
    loadResultsForInterview,
    resetSession,
    sessionBusy,
    sessionError,
  } = useInterview()

  useEffect(() => {
    if (interviewId && results.categories.length === 0) {
      void loadResultsForInterview(interviewId)
    }
  }, [interviewId, results.categories.length, loadResultsForInterview])

  const hasResults = results.categories.length > 0 || results.overallScore > 0

  return (
    <div className="animate-fade-in space-y-8">
      <header className="flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <p className="text-sm font-medium text-accent-purple">Session complete</p>
          <h1 className="font-display text-3xl text-navy">Your results</h1>
          <p className="mt-1 text-navy-muted">
            {config.jobRole} ·{' '}
            <span className="capitalize">{config.interviewCategory.replace('-', ' ')}</span>
          </p>
        </div>
        {(resultsIllustrative || isDemoMode) && (
          <div
            className="flex items-center gap-2 rounded-xl border border-amber-200 bg-amber-50 px-4 py-2 text-sm text-amber-900"
            role="note"
          >
            <AlertCircle className="h-4 w-4 shrink-0" aria-hidden />
            {isDemoMode
              ? 'Illustrative demo scores — not saved to Supabase or Gemini.'
              : resultsIllustrative
                ? 'Sample scores — not from Gemini.'
                : 'Scores and feedback generated by Gemini and saved to Supabase.'}
          </div>
        )}
      </header>

      {sessionError && (
        <div className="rounded-xl border border-red-200 bg-red-50 p-3 text-sm text-red-900" role="alert">
          {sessionError}
        </div>
      )}

      {sessionBusy && !hasResults ? (
        <div className="flex items-center justify-center gap-2 py-16 text-navy-muted">
          <Loader2 className="h-6 w-6 animate-spin text-accent-purple" aria-hidden />
          Loading results from Supabase…
        </div>
      ) : !hasResults ? (
        <div className="rounded-2xl border border-lavender-100 bg-white p-8 text-center shadow-card">
          <p className="text-navy-muted">No results for this session yet.</p>
          <Link to="/setup" className="mt-4 inline-block text-accent-purple">
            Start a new interview
          </Link>
        </div>
      ) : (
        <>
          <div className="grid gap-6 lg:grid-cols-3">
            <div className="rounded-2xl border border-lavender-100 bg-white p-8 text-center shadow-card lg:col-span-1">
              <div className="mx-auto flex h-28 w-28 items-center justify-center rounded-full bg-gradient-to-br from-lavender-100 to-lavender-200">
                <span className="font-display text-4xl text-accent-purple">
                  {results.overallScore}
                </span>
              </div>
              <p className="mt-4 text-sm font-medium text-navy-muted">Overall score</p>
              <p className="mt-1 text-xs text-navy-soft">Saved in interview_results</p>
            </div>

            <div className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card lg:col-span-2">
              <h2 className="flex items-center gap-2 text-lg font-semibold text-navy">
                <TrendingUp className="h-5 w-5 text-accent-purple" aria-hidden />
                Category breakdown
              </h2>
              <ul className="mt-5 space-y-4">
                {results.categories.map((cat) => (
                  <li key={cat.label}>
                    <div className="flex justify-between text-sm">
                      <span className="text-navy-muted">{cat.label}</span>
                      <span className="font-semibold text-navy">{cat.score}%</span>
                    </div>
                    <div className="mt-1.5 h-2 overflow-hidden rounded-full bg-lavender-100">
                      <div
                        className="h-full rounded-full bg-gradient-to-r from-accent-violet to-accent-purple transition-all duration-700"
                        style={{ width: `${cat.score}%` }}
                      />
                    </div>
                  </li>
                ))}
              </ul>
            </div>
          </div>

          <div className="grid gap-6 md:grid-cols-2">
            <section className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card">
              <h2 className="flex items-center gap-2 font-semibold text-navy">
                <CheckCircle2 className="h-5 w-5 text-emerald-500" aria-hidden />
                Strengths
              </h2>
              <ul className="mt-4 space-y-3">
                {results.strengths.map((item) => (
                  <li
                    key={item}
                    className="flex gap-2 text-sm leading-relaxed text-navy-muted"
                  >
                    <span className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-emerald-400" />
                    {item}
                  </li>
                ))}
              </ul>
            </section>

            <section className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card">
              <h2 className="flex items-center gap-2 font-semibold text-navy">
                <Sparkles className="h-5 w-5 text-accent-violet" aria-hidden />
                Areas to improve
              </h2>
              <ul className="mt-4 space-y-3">
                {results.improvements.map((item) => (
                  <li
                    key={item}
                    className="flex gap-2 text-sm leading-relaxed text-navy-muted"
                  >
                    <span className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-accent-violet" />
                    {item}
                  </li>
                ))}
              </ul>
            </section>
          </div>

          {results.questionFeedback && results.questionFeedback.length > 0 && (
            <section className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card">
              <h2 className="font-semibold text-navy">Question-by-question feedback</h2>
              <ul className="mt-4 space-y-4">
                {results.questionFeedback.map((item) => (
                  <li key={item.question} className="border-b border-lavender-50 pb-4 last:border-0">
                    <p className="text-sm font-medium text-navy">{item.question}</p>
                    <p className="text-xs text-accent-purple">Score: {item.score}/100</p>
                    <p className="mt-1 text-sm text-navy-muted">{item.feedback}</p>
                    {item.exampleImprovement && (
                      <p className="mt-1 text-xs text-navy-soft">Example: {item.exampleImprovement}</p>
                    )}
                  </li>
                ))}
              </ul>
            </section>
          )}

          {results.studyTopics && results.studyTopics.length > 0 && (
            <section className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card">
              <h2 className="font-semibold text-navy">Suggested study topics</h2>
              <ul className="mt-3 list-disc pl-5 text-sm text-navy-muted">
                {results.studyTopics.map((t) => (
                  <li key={t}>{t}</li>
                ))}
              </ul>
            </section>
          )}

          {results.summary && (
            <section className="rounded-2xl border border-lavender-100 bg-white p-6 shadow-card">
              <h2 className="font-semibold text-navy">Summary</h2>
              <p className="mt-3 text-sm leading-relaxed text-navy-muted">{results.summary}</p>
            </section>
          )}

          <section className="rounded-2xl border border-lavender-100 bg-gradient-to-br from-lavender-50 to-white p-6 shadow-card">
            <h2 className="font-semibold text-navy">Recommended next steps</h2>
            <ol className="mt-4 list-decimal space-y-2 pl-5 text-sm text-navy-muted">
              {results.recommendations.map((rec) => (
                <li key={rec}>{rec}</li>
              ))}
            </ol>
          </section>
        </>
      )}

      <div className="flex flex-col gap-3 sm:flex-row">
        <Link
          to="/setup"
          onClick={() => resetSession()}
          className="inline-flex flex-1 items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-accent-violet to-accent-purple py-3 text-sm font-semibold text-white shadow-glow"
        >
          <RotateCcw className="h-4 w-4" aria-hidden />
          Practice again
        </Link>
        <Link
          to="/"
          className="inline-flex flex-1 items-center justify-center gap-2 rounded-xl border border-lavender-200 bg-white py-3 text-sm font-semibold text-navy"
        >
          <ArrowLeft className="h-4 w-4" aria-hidden />
          Back to dashboard
        </Link>
      </div>
    </div>
  )
}
