import { useEffect, useState } from 'react'
import { useNavigate } from 'react-router-dom'
import { Briefcase, ChevronRight, Layers, Loader2, Sliders } from 'lucide-react'
import { useInterview } from '../context/InterviewContext'
import { useAuth } from '../context/AuthContext'
import { fetchProfile } from '../services/profileService'
import type { Difficulty, ExperienceLevel, InterviewCategory, QuestionCount } from '../types/interview'

const experienceOptions: { value: ExperienceLevel; label: string }[] = [
  { value: 'fresher', label: 'Fresher' },
  { value: 'entry', label: 'Entry level' },
  { value: 'experienced', label: 'Experienced' },
]

const categoryOptions: { value: InterviewCategory; label: string; desc: string }[] = [
  { value: 'technical', label: 'Technical', desc: 'Role-specific technical questions' },
  { value: 'hr', label: 'HR Interview', desc: 'Behavioral & culture fit' },
  { value: 'aptitude', label: 'Aptitude', desc: 'Numerical & reasoning' },
  { value: 'logical-reasoning', label: 'Logical Reasoning', desc: 'Puzzles & structured thinking' },
  { value: 'mixed', label: 'Mixed', desc: 'Balanced mock interview' },
]

const difficultyOptions: { value: Difficulty; label: string }[] = [
  { value: 'easy', label: 'Easy' },
  { value: 'medium', label: 'Medium' },
  { value: 'hard', label: 'Hard' },
]

const countOptions: QuestionCount[] = [5, 10, 15]

const roleSuggestions = [
  'Data Analyst',
  'Data Scientist',
  'Python Developer',
  'Software Engineer',
  'AI/ML Engineer',
  'Web Developer',
  'Business Analyst',
]

export function Setup() {
  const navigate = useNavigate()
  const { user, isDemoMode } = useAuth()
  const { config, setConfig, startSession, sessionBusy, sessionError, clearSessionError } =
    useInterview()
  const [submitting, setSubmitting] = useState(false)
  const [resumeAttached, setResumeAttached] = useState(false)
  const [formError, setFormError] = useState<string | null>(null)

  useEffect(() => {
    if (isDemoMode) return
    if (!user) return
    fetchProfile(user.id).then((p) => {
      if (p?.full_name) setConfig({ candidateName: p.full_name })
      if (p?.target_job_role) setConfig({ jobRole: p.target_job_role })
      if (p?.resume_text_excerpt) {
        setConfig({ resumeExcerpt: p.resume_text_excerpt })
        setResumeAttached(true)
      }
    })
  }, [user, isDemoMode, setConfig])

  const handleBegin = async () => {
    if (!isDemoMode && !user) return
    setFormError(null)
    if (!config.candidateName.trim()) {
      setFormError('Please enter your name.')
      return
    }
    if (!isDemoMode && !config.resumeExcerpt) {
      setFormError('Upload your resume on the profile page before starting.')
      return
    }
    clearSessionError()
    setSubmitting(true)
    const ok = await startSession()
    setSubmitting(false)
    if (ok) navigate('/interview')
  }

  return (
    <div className="animate-fade-in mx-auto max-w-2xl space-y-8">
      <header>
        <p className="text-sm font-medium text-accent-purple">Interview setup</p>
        <h1 className="font-display text-3xl text-navy">Configure your mock interview</h1>
        <p className="mt-2 text-navy-muted">
          {isDemoMode
            ? 'Demo mode uses illustrative questions only (no Gemini).'
            : 'Questions are generated by Gemini from your resume and role.'}
        </p>
      </header>

      {formError && (
        <div className="rounded-xl border border-amber-200 bg-amber-50 p-4 text-sm text-amber-900" role="alert">
          {formError}
        </div>
      )}

      {sessionError && (
        <div className="rounded-xl border border-red-200 bg-red-50 p-4 text-sm text-red-900" role="alert">
          {sessionError}
        </div>
      )}

      <form
        className="space-y-6"
        onSubmit={(e) => {
          e.preventDefault()
          void handleBegin()
        }}
      >
        <fieldset className="rounded-2xl border border-lavender-100 bg-white p-5 shadow-card sm:p-6 space-y-4">
          <legend className="text-sm font-semibold text-navy">Candidate</legend>
          <label className="block text-sm font-medium text-navy-muted">
            Full name *
            <input
              required
              value={config.candidateName}
              onChange={(e) => setConfig({ candidateName: e.target.value })}
              className="mt-1 w-full rounded-xl border border-lavender-200 px-4 py-3"
            />
          </label>
          {!isDemoMode && (
            <p className="text-xs text-navy-soft">
              Resume:{' '}
              {resumeAttached ? (
                <span className="text-emerald-700">Attached from profile</span>
              ) : (
                <a href="/profile" className="text-accent-purple underline">Upload on profile page</a>
              )}
            </p>
          )}
        </fieldset>

        <fieldset className="rounded-2xl border border-lavender-100 bg-white p-5 shadow-card sm:p-6">
          <legend className="flex items-center gap-2 px-1 text-sm font-semibold text-navy">
            <Briefcase className="h-4 w-4 text-accent-purple" aria-hidden />
            Target job role *
          </legend>
          <input
            type="text"
            list="roles"
            value={config.jobRole}
            onChange={(e) => setConfig({ jobRole: e.target.value })}
            className="mt-3 w-full rounded-xl border border-lavender-200 px-4 py-3"
            required
          />
          <datalist id="roles">
            {roleSuggestions.map((role) => (
              <option key={role} value={role} />
            ))}
          </datalist>
        </fieldset>

        <fieldset className="rounded-2xl border border-lavender-100 bg-white p-5 shadow-card sm:p-6">
          <legend className="flex items-center gap-2 text-sm font-semibold text-navy">
            <Layers className="h-4 w-4 text-accent-purple" aria-hidden />
            Interview category
          </legend>
          <div className="mt-3 grid gap-2 sm:grid-cols-2">
            {categoryOptions.map((opt) => (
              <label
                key={opt.value}
                className={[
                  'cursor-pointer rounded-xl border px-4 py-3 transition',
                  config.interviewCategory === opt.value
                    ? 'border-accent-violet bg-lavender-50'
                    : 'border-lavender-100',
                ].join(' ')}
              >
                <input
                  type="radio"
                  name="category"
                  className="sr-only"
                  checked={config.interviewCategory === opt.value}
                  onChange={() => setConfig({ interviewCategory: opt.value })}
                />
                <span className="block text-sm font-medium">{opt.label}</span>
                <span className="text-xs text-navy-soft">{opt.desc}</span>
              </label>
            ))}
          </div>
        </fieldset>

        <fieldset className="rounded-2xl border border-lavender-100 bg-white p-5 shadow-card sm:p-6 space-y-4">
          <legend className="flex items-center gap-2 text-sm font-semibold text-navy">
            <Sliders className="h-4 w-4 text-accent-purple" aria-hidden />
            Options
          </legend>
          <div>
            <p className="text-xs text-navy-soft">Experience</p>
            <div className="mt-2 flex flex-wrap gap-2">
              {experienceOptions.map((opt) => (
                <label
                  key={opt.value}
                  className={[
                    'cursor-pointer rounded-full border px-4 py-2 text-sm',
                    config.experienceLevel === opt.value
                      ? 'border-accent-violet bg-accent-purple text-white'
                      : 'border-lavender-200',
                  ].join(' ')}
                >
                  <input type="radio" name="exp" className="sr-only" checked={config.experienceLevel === opt.value} onChange={() => setConfig({ experienceLevel: opt.value })} />
                  {opt.label}
                </label>
              ))}
            </div>
          </div>
          <div>
            <p className="text-xs text-navy-soft">Difficulty</p>
            <div className="mt-2 flex flex-wrap gap-2">
              {difficultyOptions.map((opt) => (
                <label
                  key={opt.value}
                  className={[
                    'cursor-pointer rounded-full border px-4 py-2 text-sm',
                    config.difficulty === opt.value
                      ? 'border-accent-violet bg-lavender-50 text-accent-purple'
                      : 'border-lavender-200',
                  ].join(' ')}
                >
                  <input type="radio" name="diff" className="sr-only" checked={config.difficulty === opt.value} onChange={() => setConfig({ difficulty: opt.value })} />
                  {opt.label}
                </label>
              ))}
            </div>
          </div>
          <div>
            <p className="text-xs text-navy-soft">Number of questions</p>
            <div className="mt-2 flex gap-2">
              {countOptions.map((n) => (
                <label
                  key={n}
                  className={[
                    'cursor-pointer rounded-full border px-4 py-2 text-sm',
                    config.questionCount === n
                      ? 'border-accent-violet bg-accent-purple text-white'
                      : 'border-lavender-200',
                  ].join(' ')}
                >
                  <input type="radio" name="count" className="sr-only" checked={config.questionCount === n} onChange={() => setConfig({ questionCount: n })} />
                  {n}
                </label>
              ))}
            </div>
          </div>
          <label className="block text-sm font-medium text-navy-muted">
            Job description (optional)
            <textarea
              rows={3}
              value={config.jobDescription ?? ''}
              onChange={(e) => setConfig({ jobDescription: e.target.value })}
              className="mt-1 w-full rounded-xl border border-lavender-200 px-4 py-3"
              placeholder="Paste a job posting snippet for tighter question focus…"
            />
          </label>
        </fieldset>

        <button
          type="submit"
          disabled={submitting || sessionBusy}
          className="flex w-full items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-accent-violet to-accent-purple py-3.5 text-sm font-semibold text-white disabled:opacity-60"
        >
          {(submitting || sessionBusy) && <Loader2 className="h-4 w-4 animate-spin" aria-hidden />}
          Start interview
          <ChevronRight className="h-4 w-4" aria-hidden />
        </button>
      </form>
    </div>
  )
}
